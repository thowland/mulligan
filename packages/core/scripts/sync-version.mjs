// Writes src/version.ts from package.json so LIBRARY_VERSION is always the published version.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
  new URL('../src/version.ts', import.meta.url),
  `// Generated by scripts/sync-version.mjs from package.json. Do not edit.\nexport const LIBRARY_VERSION = '${version}';\n`,
);
console.log(`LIBRARY_VERSION = ${version}`);
